<?php

namespace App\Services;

use Dompdf\Canvas;
use Dompdf\Dompdf;
use Dompdf\FontMetrics;

/**
 * Draws the fundis list straight onto a Dompdf canvas.
 *
 * Dompdf's HTML layout needs about 0.4MB per table row and runs out of 1GB
 * before 2,000 rows. Drawing skips the layout step, so 50,000 rows take a few
 * seconds and about 110MB.
 */
class FundiListPdf
{
    /**
     * Largest export offered as a PDF. Excel has no limit.
     */
    public const MAX_ROWS = 50000;

    private const MARGIN = 30;

    private const FOOTER_HEIGHT = 30;

    private const FONT_SIZE = 8;

    private const LINE_HEIGHT = 10;

    private const CELL_PADDING = 3;

    private const BORDER_COLOR = [0.6, 0.6, 0.6];

    private const HEADER_COLOR = [0.973, 0.976, 0.98];

    private const FOOTER_COLOR = [0.4, 0.4, 0.4];

    /**
     * Column heading => width in points, adding up to the width of landscape A4.
     */
    private const COLUMNS = [
        'Name' => 190,
        'Address' => 240,
        'Primary Phone' => 90,
        'Trans. Phone' => 90,
        'Gender' => 50,
        'Sites' => 56,
        'Bags' => 56,
    ];

    private Canvas $canvas;

    private FontMetrics $metrics;

    private string $font;

    private string $boldFont;

    private float $y;

    public function __construct(string $title, string $date)
    {
        $dompdf = new Dompdf;
        $dompdf->setPaper('A4', 'landscape');

        $this->canvas = $dompdf->getCanvas();
        $this->metrics = $dompdf->getFontMetrics();
        $this->font = $this->metrics->getFont('Helvetica');
        $this->boldFont = $this->metrics->getFont('Helvetica', 'bold');

        $this->drawFirstPageHeading($title, $date);
        $this->drawFooter();
        $this->drawColumnHeadings();
    }

    /**
     * @param  array<int, mixed>  $cells  One value per column, in column order.
     */
    public function addRow(array $cells): void
    {
        $lines = [];
        foreach (array_values(self::COLUMNS) as $index => $width) {
            $lines[$index] = $this->wrap((string) ($cells[$index] ?? ''), $width - 2 * self::CELL_PADDING, $this->font);
        }

        $height = $this->rowHeight($lines);

        if ($this->y + $height > $this->bottom()) {
            $this->canvas->new_page();
            $this->y = self::MARGIN;
            $this->drawFooter();
            $this->drawColumnHeadings();
        }

        $this->drawRow($lines, $height, $this->font);
    }

    public function output(): string
    {
        return $this->canvas->output();
    }

    private function drawFirstPageHeading(string $title, string $date): void
    {
        $this->y = self::MARGIN;

        $logo = public_path('images/logo.png');
        [$width, $height] = getimagesize($logo);
        $this->canvas->image($logo, self::MARGIN, $this->y, 30 * $width / $height, 30);
        $this->y += 40;

        $this->canvas->text(self::MARGIN, $this->y, $title, $this->boldFont, 14);

        $dateWidth = $this->metrics->getTextWidth($date, $this->font, 10);
        $this->canvas->text($this->canvas->get_width() - self::MARGIN - $dateWidth, $this->y + 3, $date, $this->font, 10);
        $this->y += 24;
    }

    private function drawFooter(): void
    {
        $y = $this->canvas->get_height() - self::MARGIN + 6;
        $note = 'Generated by Magic Builders on '.date('Y-m-d H:i:s')
            .'. This document is confidential and intended for internal use only.';

        $this->canvas->text(self::MARGIN, $y, $note, $this->font, 7, self::FOOTER_COLOR);

        $page = 'Page '.($this->canvas->get_page_number());
        $pageWidth = $this->metrics->getTextWidth($page, $this->font, 7);
        $this->canvas->text($this->canvas->get_width() - self::MARGIN - $pageWidth, $y, $page, $this->font, 7, self::FOOTER_COLOR);
    }

    private function drawColumnHeadings(): void
    {
        $lines = array_map(fn ($heading) => [$heading], array_keys(self::COLUMNS));
        $height = $this->rowHeight($lines);

        $tableWidth = array_sum(self::COLUMNS);
        $this->canvas->filled_rectangle(self::MARGIN, $this->y, $tableWidth, $height, self::HEADER_COLOR);

        $this->drawRow($lines, $height, $this->boldFont);
    }

    /**
     * @param  array<int, array<int, string>>  $lines  Wrapped text lines for each column.
     */
    private function drawRow(array $lines, float $height, string $font): void
    {
        $x = self::MARGIN;

        foreach (array_values(self::COLUMNS) as $index => $width) {
            $this->canvas->rectangle($x, $this->y, $width, $height, self::BORDER_COLOR, 0.5);

            foreach ($lines[$index] as $lineNumber => $line) {
                $this->canvas->text(
                    $x + self::CELL_PADDING,
                    $this->y + self::CELL_PADDING + $lineNumber * self::LINE_HEIGHT,
                    $line,
                    $font,
                    self::FONT_SIZE
                );
            }

            $x += $width;
        }

        $this->y += $height;
    }

    /**
     * @param  array<int, array<int, string>>  $lines
     */
    private function rowHeight(array $lines): float
    {
        return max(array_map('count', $lines)) * self::LINE_HEIGHT + 2 * self::CELL_PADDING;
    }

    private function bottom(): float
    {
        return $this->canvas->get_height() - self::MARGIN - self::FOOTER_HEIGHT;
    }

    /**
     * Split text into lines that fit the given width, so nothing gets cut off.
     *
     * @return array<int, string>
     */
    private function wrap(string $text, float $width, string $font): array
    {
        $lines = [];
        $line = '';

        foreach (preg_split('/\s+/u', trim($text), -1, PREG_SPLIT_NO_EMPTY) ?: [] as $word) {
            $candidate = $line === '' ? $word : "{$line} {$word}";

            if ($this->fits($candidate, $width, $font)) {
                $line = $candidate;

                continue;
            }

            if ($line !== '') {
                $lines[] = $line;
            }

            // A single word wider than the column gets broken across lines.
            while (! $this->fits($word, $width, $font) && mb_strlen($word) > 1) {
                $length = mb_strlen($word) - 1;
                while ($length > 1 && ! $this->fits(mb_substr($word, 0, $length), $width, $font)) {
                    $length--;
                }

                $lines[] = mb_substr($word, 0, $length);
                $word = mb_substr($word, $length);
            }

            $line = $word;
        }

        if ($line !== '') {
            $lines[] = $line;
        }

        return $lines ?: [''];
    }

    private function fits(string $text, float $width, string $font): bool
    {
        return $this->metrics->getTextWidth($text, $font, self::FONT_SIZE) <= $width;
    }
}
